@lazySingleton
class GetLabelsUseCase {
  final SmartConfiguratorRepository _smartConfiguratorRepository;
  final GetSecureStoredUserInfoUseCase _getSecureStoredUserInfoUseCase;
  final GetStoredCorporateIdUseCase _getStoredCorporateIdUseCase;

  GetLabelsUseCase(
    this._smartConfiguratorRepository,
    this._getSecureStoredUserInfoUseCase,
    this._getStoredCorporateIdUseCase,
  );

  Future<Either<Failure, Map<String, String>>> call(String langCode) async {
    /// Get initiativeId
    UserInfoModel? userInfoModel = await _getSecureStoredUserInfoUseCase();
    int? initiativeId = userInfoModel?.initiativeId;

    /// Get corporateID
    final corporateId = (await _getStoredCorporateIdUseCase())?.id;

    return _smartConfiguratorRepository.getLabels(
      langCode: langCode,
      corporateId: corporateId,
      initiativeId: initiativeId,
    );
  }
}

